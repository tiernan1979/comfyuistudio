import { useEffect, useRef } from 'react'
import { createPortal } from 'react-dom'
import {
  AlertCircle,
  ArrowDown,
  ArrowUp,
  CheckCircle2,
  Clapperboard,
  Download,
  FileJson,
  ImagePlus,
  Loader2,
  Play,
  Plus,
  Square,
  Trash2,
  X,
} from 'lucide-react'
import useStore from '../store/useStore'
import { saveBlobAs } from '../lib/comfyui'
import { useFocusTrap } from '../hooks/useFocusTrap'
import useEpisodeRunner from '../hooks/useEpisodeRunner'

const STATUS = {
  draft: 'bg-bg-hover text-text-muted',
  running: 'bg-accent/20 text-accent',
  done: 'bg-emerald-500/15 text-emerald-300',
  error: 'bg-rose-500/15 text-rose-300',
}

function stillOf(shot) {
  return shot.still || ''
}

export default function EpisodePanel({ open, onClose, generate }) {
  const panelRef = useRef(null)
  const shots = useStore((s) => s.episodeShots)
  const addEpisodeShot = useStore((s) => s.addEpisodeShot)
  const updateEpisodeShot = useStore((s) => s.updateEpisodeShot)
  const removeEpisodeShot = useStore((s) => s.removeEpisodeShot)
  const setEpisodeShots = useStore((s) => s.setEpisodeShots)
  const prompt = useStore((s) => s.prompt)
  const outputImage = useStore((s) => s.outputImage)
  const generating = useStore((s) => s.generating)
  const videoSourceImage = useStore((s) => s.videoSourceImage)
  const videoSettings = useStore((s) => s.videoSettings)
  const videoTitle = useStore((s) => s.titles?.video)
  const runner = useEpisodeRunner(generate)

  useFocusTrap(panelRef, open)

  useEffect(() => {
    if (!open) return
    const onKey = (e) => {
      if (e.key === 'Escape' && !runner.running) onClose()
    }
    window.addEventListener('keydown', onKey)
    return () => window.removeEventListener('keydown', onKey)
  }, [open, runner.running, onClose])

  if (!open) return null

  const doneCount = shots.filter((s) => s.status === 'done').length
  const totalSeconds = shots.reduce((sum, s) => sum + (Number(s.seconds) || 0), 0)
  const currentStill = outputImage || videoSourceImage?.url || videoSourceImage?.preview || ''

  const addShot = () => {
    const n = shots.length + 1
    addEpisodeShot({
      prompt: prompt.trim() || `Shot ${n}`,
      seconds: Number(videoSettings.duration) || 5.2,
      still: currentStill,
      name: videoTitle || `shot-${n}`,
    })
  }

  const move = (index, delta) => {
    const next = [...shots]
    const target = index + delta
    if (target < 0 || target >= next.length) return
    const [row] = next.splice(index, 1)
    next.splice(target, 0, row)
    setEpisodeShots(next)
  }

  const exportManifest = () => {
    const payload = {
      title: videoTitle || 'episode',
      exportedAt: new Date().toISOString(),
      shots: shots.map((shot, i) => ({
        index: i + 1,
        id: shot.id,
        prompt: shot.prompt || '',
        seconds: Number(shot.seconds) || 0,
        status: shot.status || 'draft',
        still: stillOf(shot) || null,
        outputUrl: shot.outputUrl || null,
      })),
    }
    saveBlobAs(
      new Blob([JSON.stringify(payload, null, 2)], { type: 'application/json' }),
      'episode-manifest.json',
    )
  }

  const exportStitch = () => {
    const finished = shots.filter((s) => s.status === 'done' && s.outputUrl)
    const lines = [
      '#!/usr/bin/env bash',
      '# Generated by ComfyUI Studio. Downloads finished shots, then stitches',
      '# them without re-encoding (all H3 clips share the same codec/size).',
      'set -euo pipefail',
      '',
    ]
    if (!finished.length) {
      lines.push('echo "No finished shots yet — render some first."', 'exit 1')
    } else {
      finished.forEach((shot, i) => {
        const name = `shot-${String(i + 1).padStart(3, '0')}.mp4`
        const url = String(shot.outputUrl).replace(/'/g, '%27')
        lines.push(`curl -fsSL -o "${name}" '${url}'`)
      })
      lines.push(': > shots.txt')
      finished.forEach((shot, i) => {
        const name = `shot-${String(i + 1).padStart(3, '0')}.mp4`
        lines.push(`printf "file '%s'\\n" "${name}" >> shots.txt`)
      })
      lines.push('ffmpeg -y -f concat -safe 0 -i shots.txt -c copy episode.mp4')
      lines.push('echo "Wrote episode.mp4"')
    }
    saveBlobAs(
      new Blob([lines.join('\n')], { type: 'text/x-shellscript' }),
      'episode-stitch.sh',
    )
  }

  return createPortal(
    <div className="fixed inset-0 z-50 flex items-center justify-center p-3 sm:p-6">
      <div
        className="absolute inset-0 bg-black/70 backdrop-blur-sm"
        onClick={() => !runner.running && onClose()}
      />
      <div
        ref={panelRef}
        role="dialog"
        aria-modal="true"
        aria-label="Episode shot planner"
        className="relative flex max-h-[92vh] w-full max-w-4xl flex-col overflow-hidden rounded-2xl border border-border bg-bg-secondary shadow-2xl"
      >
        <div className="flex items-start justify-between gap-3 border-b border-border px-4 py-3 sm:px-5">
          <div>
            <h2 className="flex items-center gap-2 text-sm font-semibold text-text-primary">
              <Clapperboard size={16} className="text-accent" />
              Episode shots
            </h2>
            <p className="mt-0.5 text-[11px] text-text-muted">
              Each shot renders independently, so a failed take can be retried without redoing the
              whole episode.
            </p>
          </div>
          <button
            type="button"
            onClick={onClose}
            disabled={runner.running}
            aria-label="Close episode planner"
            className="rounded-lg p-1.5 text-text-muted transition-colors hover:bg-bg-hover hover:text-text-primary disabled:opacity-40 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-accent/60"
          >
            <X size={17} />
          </button>
        </div>

        <div className="flex flex-wrap items-center gap-2 border-b border-border bg-bg-card/40 px-4 py-2.5 sm:px-5">
          <button
            type="button"
            onClick={addShot}
            disabled={runner.running}
            className="flex items-center gap-1.5 rounded-lg border border-border bg-bg-card px-3 py-1.5 text-xs font-medium text-text-secondary transition-colors hover:bg-bg-hover hover:text-text-primary disabled:opacity-40"
          >
            <Plus size={13} /> Add shot
          </button>
          <button
            type="button"
            onClick={runner.run}
            disabled={runner.running || generating || !shots.some((s) => s.status !== 'done')}
            title={generating && !runner.running ? 'Wait for the current render to finish' : undefined}
            className="flex items-center gap-1.5 rounded-lg bg-accent px-3 py-1.5 text-xs font-semibold text-white transition-colors hover:bg-accent-hover disabled:opacity-40"
          >
            {runner.running ? <Loader2 size={13} className="animate-spin" /> : <Play size={13} />}
            {runner.running ? 'Rendering…' : generating ? 'Render running…' : 'Run pending'}
          </button>
          {runner.running && (
            <button
              type="button"
              onClick={runner.stop}
              className="flex items-center gap-1.5 rounded-lg border border-rose-500/40 px-3 py-1.5 text-xs font-medium text-rose-300 transition-colors hover:bg-rose-500/10"
            >
              <Square size={11} fill="currentColor" /> Stop
            </button>
          )}
          <button
            type="button"
            onClick={() => setEpisodeShots(shots.filter((s) => s.status !== 'done'))}
            disabled={runner.running || !doneCount}
            className="rounded-lg px-2.5 py-1.5 text-xs text-text-muted transition-colors hover:bg-bg-hover hover:text-text-primary disabled:opacity-40"
          >
            Clear done
          </button>
          <div className="ml-auto flex items-center gap-2">
            <button
              type="button"
              onClick={exportManifest}
              disabled={!shots.length}
              className="flex items-center gap-1.5 rounded-lg border border-border px-2.5 py-1.5 text-xs text-text-secondary transition-colors hover:bg-bg-hover disabled:opacity-40"
            >
              <FileJson size={13} /> Manifest
            </button>
            <button
              type="button"
              onClick={exportStitch}
              disabled={!doneCount}
              className="flex items-center gap-1.5 rounded-lg border border-border px-2.5 py-1.5 text-xs text-text-secondary transition-colors hover:bg-bg-hover disabled:opacity-40"
            >
              <Download size={13} /> Stitch kit
            </button>
          </div>
        </div>

        <div className="min-h-0 flex-1 overflow-y-auto p-3 sm:p-4">
          {!shots.length ? (
            <div className="flex flex-col items-center justify-center gap-2 rounded-xl border border-dashed border-border py-12 text-center">
              <Clapperboard size={26} className="text-text-muted" />
              <p className="text-sm text-text-secondary">No shots yet</p>
              <p className="max-w-sm text-[11px] text-text-muted">
                Add the current prompt and still as shot 1, then keep adding shots for the episode.
                Animate only the key moments — stills and slow pans can carry the rest.
              </p>
            </div>
          ) : (
            <div className="space-y-2">
              {shots.map((shot, index) => {
                const isCurrent = runner.currentId === shot.id
                const status = STATUS[shot.status] ? shot.status : 'draft'
                return (
                  <div
                    key={shot.id}
                    className={
                      'rounded-xl border bg-bg-card/60 p-2.5 transition-colors ' +
                      (isCurrent ? 'border-accent/60 ring-1 ring-accent/30' : 'border-border/80')
                    }
                  >
                    <div className="flex gap-2.5">
                      <div className="w-16 shrink-0">
                        {shot.still ? (
                          <img
                            src={shot.still}
                            alt=""
                            className="h-16 w-16 rounded-lg border border-border object-cover"
                          />
                        ) : (
                          <div className="flex h-16 w-16 items-center justify-center rounded-lg border border-dashed border-border text-text-muted">
                            <ImagePlus size={16} />
                          </div>
                        )}
                      </div>
                      <div className="min-w-0 flex-1 space-y-1.5">
                        <div className="flex items-center gap-2">
                          <span className="text-[10px] font-semibold tabular-nums text-text-muted">
                            {String(index + 1).padStart(2, '0')}
                          </span>
                          <span
                            className={`rounded-full px-2 py-0.5 text-[10px] font-medium ${STATUS[status]}`}
                          >
                            {status === 'running' ? 'rendering' : status}
                          </span>
                          {shot.error && status === 'error' && (
                            <span className="truncate text-[10px] text-rose-300" title={shot.error}>
                              {shot.error}
                            </span>
                          )}
                          {shot.status === 'done' && shot.outputUrl && (
                            <a
                              href={shot.outputUrl}
                              target="_blank"
                              rel="noreferrer"
                              className="ml-auto flex items-center gap-1 text-[10px] text-emerald-300 hover:underline"
                            >
                              <CheckCircle2 size={11} /> Open clip
                            </a>
                          )}
                        </div>
                        <textarea
                          value={shot.prompt || ''}
                          onChange={(e) => updateEpisodeShot(shot.id, { prompt: e.target.value })}
                          rows={2}
                          disabled={runner.running}
                          placeholder="What happens in this shot?"
                          className="w-full resize-y rounded-lg border border-border bg-bg-secondary px-2.5 py-1.5 text-xs text-text-primary placeholder:text-text-muted focus:border-accent/60 focus:outline-none focus:ring-2 focus:ring-accent/30 disabled:opacity-60"
                        />
                        <div className="flex flex-wrap items-center gap-2">
                          <label className="flex items-center gap-1 text-[10px] text-text-muted">
                            Seconds
                            <input
                              type="number"
                              min={5.2}
                              max={15.1}
                              step={0.1}
                              value={shot.seconds ?? 5.2}
                              onChange={(e) =>
                                updateEpisodeShot(shot.id, { seconds: Number(e.target.value) })
                              }
                              disabled={runner.running}
                              className="w-16 rounded-md border border-border bg-bg-secondary px-1.5 py-0.5 text-[11px] tabular-nums text-text-primary focus:border-accent/60 focus:outline-none"
                            />
                          </label>
                          <button
                            type="button"
                            onClick={() =>
                              updateEpisodeShot(shot.id, {
                                still: currentStill,
                                name: videoTitle || `shot-${index + 1}`,
                              })
                            }
                            disabled={runner.running || !currentStill}
                            className="flex items-center gap-1 rounded-md px-1.5 py-0.5 text-[10px] text-text-muted transition-colors hover:bg-bg-hover hover:text-text-primary disabled:opacity-40"
                          >
                            <ImagePlus size={11} /> Use current image
                          </button>
                          {shot.still && (
                            <button
                              type="button"
                              onClick={() => updateEpisodeShot(shot.id, { still: '' })}
                              disabled={runner.running}
                              className="rounded-md px-1.5 py-0.5 text-[10px] text-text-muted transition-colors hover:bg-bg-hover hover:text-text-primary disabled:opacity-40"
                            >
                              Clear still
                            </button>
                          )}
                          <button
                            type="button"
                            onClick={() => updateEpisodeShot(shot.id, { status: 'draft', error: '' })}
                            disabled={runner.running || shot.status === 'draft'}
                            className="flex items-center gap-1 rounded-md px-1.5 py-0.5 text-[10px] text-text-muted transition-colors hover:bg-bg-hover hover:text-text-primary disabled:opacity-40"
                          >
                            <AlertCircle size={11} /> Reset
                          </button>
                          <div className="ml-auto flex items-center gap-0.5">
                            <button
                              type="button"
                              onClick={() => move(index, -1)}
                              disabled={runner.running || index === 0}
                              aria-label="Move shot up"
                              className="rounded p-1 text-text-muted hover:bg-bg-hover hover:text-text-primary disabled:opacity-30"
                            >
                              <ArrowUp size={12} />
                            </button>
                            <button
                              type="button"
                              onClick={() => move(index, 1)}
                              disabled={runner.running || index === shots.length - 1}
                              aria-label="Move shot down"
                              className="rounded p-1 text-text-muted hover:bg-bg-hover hover:text-text-primary disabled:opacity-30"
                            >
                              <ArrowDown size={12} />
                            </button>
                            <button
                              type="button"
                              onClick={() => removeEpisodeShot(shot.id)}
                              disabled={runner.running}
                              aria-label="Delete shot"
                              className="rounded p-1 text-text-muted hover:bg-rose-500/15 hover:text-rose-300 disabled:opacity-30"
                            >
                              <Trash2 size={12} />
                            </button>
                          </div>
                        </div>
                      </div>
                    </div>
                  </div>
                )
              })}
            </div>
          )}
        </div>

        <div className="flex flex-wrap items-center justify-between gap-2 border-t border-border bg-bg-card/40 px-4 py-2 text-[10px] text-text-muted sm:px-5">
          <span>
            {shots.length} shot{shots.length === 1 ? '' : 's'} · {doneCount} done ·{' '}
            {Math.round(totalSeconds)}s planned
          </span>
          <span>
            Each shot is independent; export the stitch kit when the takes are final.
          </span>
        </div>
      </div>
    </div>,
    document.body,
  )
}
